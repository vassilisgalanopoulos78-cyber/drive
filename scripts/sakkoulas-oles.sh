#!/usr/bin/env bash
# Μετατροπή όλων των αποθηκευμένων σελίδων Sakkoulas Online του Drive σε
# Markdown, σε μία εκτέλεση, ώστε να μπαίνει στη νυχτερινή εργασία.
#
# Γιατί εδώ και όχι από τη συνομιλία. Η μετατροπή διαβάζει και γράφει αρχεία
# του Drive. Όταν γίνεται σε μηχάνημα που έχει τον φάκελο τοπικά, το κείμενο
# δεν περνά από κανένα ενδιάμεσο, οπότε είναι αδύνατο να αλλοιωθεί, και οι
# τριακόσιες σελίδες τελειώνουν σε δευτερόλεπτα. Όταν γίνεται μέσα από
# συνομιλία, κάθε κείμενο περνά από την έξοδο του μοντέλου, πράγμα που είναι
# και αργό και εκθέτει σε σιωπηλή αλλοίωση χαρακτήρων, όπως συνέβη στις
# 25.9.2026 με τη ΣτΕ 821/2022. Επομένως η μετατροπή ανήκει εδώ.
#
# Χρήση:
#     bash sakkoulas-oles.sh              (μετατροπή και αναφορά)
#     bash sakkoulas-oles.sh --dokimi     (μόνο τι θα γινόταν, χωρίς εγγραφή)
#
# Η εκτέλεση είναι επαναλήψιμη. Ό,τι έχει ήδη μετατραπεί παραλείπεται, οπότε
# μπορεί να τρέχει κάθε νύχτα και να πιάνει μόνο τις νέες σελίδες.
#
# Θέση στη νυχτερινή, αμέσως μετά τον φύλακα prepei-na-suskevastei.sh και πριν
# τη σάρωση:
#
#     bash prepei-na-suskevastei.sh || exit 0
#     bash sakkoulas-oles.sh
#     bash drive-index.sh
#     ...
#     bash drive-pack-index.sh
#
# Πριν τη σάρωση, διότι αλλιώς τα κείμενα που παρήχθησαν απόψε θα μπουν στο
# ευρετήριο την επόμενη νύχτα. Πίσω από τον φύλακα, διότι γράφει μέσα στο
# κοινό Drive και δεν πρέπει να το κάνουν δύο μηχανήματα την ίδια νύχτα, προτού
# συγχρονιστεί το πρώτο.

set -eu

DRIVE="${CLAUDE_DRIVE:-/g/Το Drive μου/Claude Νομολογία Αρθρογραφία Σχέδια οδηγίες ευρετήρια}"
PROORISMOS="${CLAUDE_SAKKOULAS_OUT:-$DRIVE/Sakkoulas σε Markdown}"
SCRIPT="$(cd "$(dirname "$0")" && pwd)/sakkoulas-se-md.py"
KATALOGOS="${CLAUDE_SAKKOULAS_LOG:-$PROORISMOS/_κατάλογος μετατροπής.tsv}"

if [ ! -d "$DRIVE" ]; then
  echo "Δεν βρέθηκε ο φάκελος του Drive: $DRIVE" >&2
  echo "Ορίστε τη μεταβλητή CLAUDE_DRIVE στη σωστή διαδρομή." >&2
  exit 2
fi

if [ ! -f "$SCRIPT" ]; then
  echo "Δεν βρέθηκε το sakkoulas-se-md.py δίπλα σε αυτό το script." >&2
  exit 2
fi

if [ "${1:-}" = "--dokimi" ]; then
  echo "Δοκιμή. Δεν γράφεται τίποτε."
  python3 "$SCRIPT" "$DRIVE"
  exit 0
fi

mkdir -p "$PROORISMOS"

# Ο φάκελος προορισμού εξαιρείται από τη σάρωση, διότι δεν περιέχει .htm, αλλά
# και για να μη δημιουργηθεί ποτέ κύκλος αν κάποτε μπει κάποιο.
python3 "$SCRIPT" "$DRIVE" --out "$PROORISMOS" --katalogos "$KATALOGOS"

echo
echo "Ο κατάλογος της μετατροπής γράφτηκε στο:"
echo "  $KATALOGOS"
echo
echo "Οι φάκελοι _files δεν αφαιρέθηκαν. Αυτό γίνεται χωριστά και ρητά, με το"
echo "sakkoulas-katharisma-files.sh, αφού ελεγχθεί ο κατάλογος."
