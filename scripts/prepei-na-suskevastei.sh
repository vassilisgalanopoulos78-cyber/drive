#!/usr/bin/env bash
# Φύλακας της νυχτερινής συσκευασίας, ώστε να μπορούν να την τρέχουν δύο
# μηχανήματα χωρίς να συγκρούονται.
#
# Το πρόβλημα. Το drive-pack-index.sh γράφει τις δέσμες shard-NNNN.txt.gz και
# το manifest.tsv μέσα στο ίδιο το Drive. Αν δύο μηχανήματα συσκευάσουν την
# ίδια νύχτα, καθένα αριθμεί τις δέσμες με βάση τη δική του τοπική κατάσταση,
# οπότε γράφουν δύο διαφορετικά περιεχόμενα στο ίδιο όνομα δέσμης. Το Drive
# είτε κρατά το ένα είτε φτιάχνει αντίγραφο με «(1)», και το manifest του ενός
# παραπέμπει σε δέσμες του άλλου. Το ευρετήριο γίνεται ασυνεπές σιωπηλά.
#
# Η λύση. Συσκευάζει όποιο μηχάνημα προλάβει, και το δεύτερο το αντιλαμβάνεται
# και παραλείπει. Κριτήριο είναι η ηλικία του manifest.tsv μέσα στο Drive, που
# είναι κοινό και για τα δύο.
#
# Χρήση, ως πρώτη γραμμή της νυχτερινής:
#     bash prepei-na-suskevastei.sh || exit 0
#
# Προαιρετικό όρισμα, οι ώρες μετά τις οποίες το ευρετήριο θεωρείται παλιό.
# Προεπιλογή είκοσι, δηλαδή μία συσκευασία το εικοσιτετράωρο.
#
# Οι δύο νυχτερινές πρέπει να απέχουν τουλάχιστον δύο ώρες, ώστε το manifest
# του πρώτου μηχανήματος να προλάβει να συγχρονιστεί πριν ξεκινήσει το δεύτερο.

set -eu

IDX="${CLAUDE_IDX:-/g/Το Drive μου/Claude Νομολογία Αρθρογραφία Σχέδια οδηγίες ευρετήρια/_Ευρετήριο Claude}"
MAN="$IDX/manifest.tsv"
ORIA_ORES="${1:-20}"

if [ ! -f "$MAN" ]; then
  echo "Δεν βρέθηκε το manifest.tsv στο $IDX. Η συσκευασία προχωρά."
  exit 0
fi

now=$(date +%s)
mt=$(stat -c %Y "$MAN" 2>/dev/null || stat -f %m "$MAN" 2>/dev/null || echo 0)

if [ "$mt" -le 0 ]; then
  echo "Δεν διαβάστηκε η ώρα του manifest.tsv. Η συσκευασία προχωρά."
  exit 0
fi

ores=$(( (now - mt) / 3600 ))

if [ "$ores" -lt "$ORIA_ORES" ]; then
  echo "Το ευρετήριο συσκευάστηκε πριν από $ores ώρες, πιθανότατα από το άλλο μηχάνημα."
  echo "Παράλειψη της συσκευασίας απόψε."
  exit 1
fi

echo "Το ευρετήριο έχει ηλικία $ores ωρών. Η συσκευασία προχωρά."
exit 0
